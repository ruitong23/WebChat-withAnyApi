export function selectLanguage(languages, fallback='en') {
  const preferred=(Array.isArray(languages)?languages.find(value=>typeof value==='string'&&value.trim()):languages)||fallback;
  return /^zh(?:[-_]|$)/i.test(String(preferred).trim())?'zh':'en';
}

const escapeRegExp=value=>value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
const pattern=new RegExp(Object.keys(english).sort((a,b)=>b.length-a.length).map(escapeRegExp).join('|'),'g');
const punctuation={'（':'(', '）':')', '：':': ', '，':', ', '。':'.', '；':'; ', '！':'!', '？':'?'};
export function createI18n(languages, fallback) {
  const language=selectLanguage(languages,fallback),locale=language==='zh'?'zh-CN':'en';
  const cache=new Map(),templateCache=new WeakMap();
  function t(source) {
    if(language==='zh')return source;
    if(cache.has(source))return cache.get(source);
    const result=Object.hasOwn(english,source)?english[source]:source.replace(pattern,key=>english[key]).replace(/[（）：，。；！？]/g,char=>punctuation[char]);
    cache.set(source,result);return result;
  }
  function ui(parts,...values) {
    let translated=templateCache.get(parts);
    if(!translated){translated=parts.map(t);templateCache.set(parts,translated);}
    let result=translated[0];for(let i=0;i<values.length;i++)result+=values[i]+translated[i+1];
    return result;
  }
  function localizeError(message) {
    if(typeof message!=='string'||language==='zh')return message;
    if(Object.hasOwn(english,message))return t(message);
    for(const prefix of ['不支持的参数：','参数超出范围：','参数类型不正确：','额外参数不能覆盖 '])if(message.startsWith(prefix))return t(prefix)+message.slice(prefix.length);
    return message;
  }
  return {language,locale,t,ui,localizeError};
}

